/// Makes the bundled shaders available at ordinary filesystem paths.
///
/// mpv's `glsl-shaders` option cannot read Flutter assets directly, so the
/// small, compressed bundle is expanded into the private application-support
/// directory once. Existing files are preserved to avoid work on every launch.
class Anime4kShaderAssets {
  static const List<String> liteShaderOrder = [
    'Anime4K_Clamp_Highlights.glsl',
    'Anime4K_Restore_CNN_M.glsl',
    'Anime4K_Restore_CNN_S.glsl',
    'Anime4K_Upscale_CNN_x2_M.glsl',
    'Anime4K_AutoDownscalePre_x2.glsl',
    'Anime4K_AutoDownscalePre_x4.glsl',
    'Anime4K_Upscale_CNN_x2_S.glsl',
  ];

  static Future<Directory> ensureInstalled() async {
    final support = await getApplicationSupportDirectory();
    final directory = Directory(p.join(support.path, 'anime4k-shaders'));
    if (!await directory.exists()) {
      await directory.create(recursive: true);
    }

    for (final entry in _compressedAnime4kShaders.entries) {
      final target = File(p.join(directory.path, entry.key));
      if (await target.exists() && await target.length() > 0) continue;
      await target.writeAsBytes(
        gzip.decode(base64Decode(entry.value)),
        flush: true,
      );
    }
    return directory;
  }
}
